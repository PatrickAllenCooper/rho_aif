#!/usr/bin/env python3
"""
Single source of truth for the RockSample tables in the paper.

Reads results/results_rocksample_{5x3,7x4,7x8,11x11}.csv and emits two LaTeX
fragments (paper/tables/rocksample_main.tex and rocksample_extended.tex) plus
a console summary. This replaces hand-typed numbers that had drifted out of
sync with the committed CSVs across three prior revisions of the paper.

RS[5,3] and RS[7,4] were run at 500 episodes x 10 seeds (5,000 episodes).
RS[7,8] and RS[11,11] were run at a reduced 100 episodes x 5 seeds
(500 episodes). All four instances now include a Flat-MC(1000) baseline
in the extended table.
"""

from pathlib import Path

import pandas as pd

RESULTS = Path(__file__).resolve().parent.parent / "results"
TABLES = Path(__file__).resolve().parent.parent / "paper" / "tables"

INSTANCES = [
    ("RS[5,3]", "results_rocksample_5x3.csv", "d=3"),
    ("RS[7,4]", "results_rocksample_7x4.csv", "d=4"),
    ("RS[7,8]", "results_rocksample_7x8.csv", "d=3"),
    ("RS[11,11]", "results_rocksample_11x11.csv", "d=2"),
]

MAIN_AGENTS = ["Greedy", "Planning ({d})", "Plan+IG w=5 ({d})", "EFE w=1 ({d})"]


def load(instance_file: str) -> pd.DataFrame:
    return pd.read_csv(RESULTS / instance_file)


def load_stats(instance_file: str) -> pd.DataFrame:
    return pd.read_csv(RESULTS / instance_file.replace(".csv", "_stats.csv"))


def tied_with_best(stats_df: pd.DataFrame, label: str, best_label: str) -> bool:
    """True iff label is the best itself, or is not significantly different
    from best_label per the seed-level Welch test (Holm-Bonferroni
    corrected), matching this row against the stats CSV's Reward rows."""
    if label == best_label:
        return True
    match = stats_df[
        (stats_df["metric"] == "Reward")
        & (
            ((stats_df["agent_a"] == label) & (stats_df["agent_b"] == best_label))
            | ((stats_df["agent_a"] == best_label) & (stats_df["agent_b"] == label))
        )
    ]
    if match.empty:
        return False
    return not bool(match.iloc[0]["significant_hb_seed_level"])


def fmt_reward(row) -> str:
    return f"${row['mean_reward']:+.2f} \\pm {row['se_reward_seed_level']:.2f}$"


def build_main_table() -> str:
    lines = [
        "% Auto-generated by experiments/build_rocksample_tables.py -- do not edit by hand.",
        "\\begin{table}[ht]",
        "\\centering",
        "\\caption{RockSample results with tree-search agents. RS[5,3] and",
        " RS[7,4]: 500 episodes $\\times$ 10 seeds (5{,}000 episodes). RS[7,8]",
        " and RS[11,11]: 100 episodes $\\times$ 5 seeds (500 episodes, reduced",
        " protocol). Greedy samples without",
        " checking. Bold: best mean reward per instance, plus any agent not",
        " significantly different from it by a seed-level Welch $t$-test with",
        " Holm--Bonferroni correction (full pairwise table in",
        " Appendix~\\ref{app:rocksample}). Reward reported as mean $\\pm$",
        " seed-level SE (SE of the per-seed means, RS[5,3]/RS[7,4]: 10 seeds;",
        " RS[7,8]/RS[11,11]: 5 seeds).",
        " Steps and Checks omitted (tree-search evaluates all actions); a",
        " Flat-MC(1000) baseline for every instance is in",
        " Appendix~\\ref{app:rocksample}, which also reports per-instance",
        " step and check counts.}",
        "\\label{tab:rocksample}",
        "\\begin{small}",
        "\\begin{tabular}{llcccc}",
        "\\toprule",
        "Instance & Agent & Good & Bad & Reward \\\\",
        "\\midrule",
    ]
    for instance, fname, depth in INSTANCES:
        df = load(fname)
        stats_df = load_stats(fname)
        rows = []
        for template in MAIN_AGENTS:
            label = template.format(d=depth)
            match = df[df["agent"] == label]
            if match.empty:
                continue
            rows.append((label, match.iloc[0]))
        best_label = max(rows, key=lambda lr: lr[1]["mean_reward"])[0]
        lines.append(f"\\multirow{{{len(rows)}}}{{*}}{{{instance}}}")
        for label, r in rows:
            is_best = tied_with_best(stats_df, label, best_label)
            reward_str = fmt_reward(r)
            if is_best:
                reward_str = f"\\mathbf{{{reward_str[1:-1]}}}"
                reward_str = f"${reward_str}$"
            disp_label = label.replace("Planning (", "Planning ($w{=}0$, ").replace(
                "Plan+IG w=5 (", "Plan+IG ($w{=}5$, "
            ).replace("EFE w=1 (", "EFE ($w{=}1$, ")
            lines.append(f" & {disp_label} & ${r['mean_good']:.2f}$ & ${r['mean_bad']:.2f}$ & {reward_str} \\\\")
        lines.append("\\midrule" if instance != INSTANCES[-1][0] else "\\bottomrule")
    if lines[-1] == "\\midrule":
        lines[-1] = "\\bottomrule"
    lines += ["\\end{tabular}", "\\end{small}", "\\end{table}", ""]
    return "\n".join(lines)


EXT_AGENT_ORDER = [
    "Greedy",
    "Flat-MC (1000)",
    "Planning ({d})",
    "Plan+IG w=5 ({d})",
    "Plan+IG w=10 ({d})",
    "EFE w=1 ({d})",
]


def build_extended_table() -> str:
    lines = [
        "% Auto-generated by experiments/build_rocksample_tables.py -- do not edit by hand.",
        "\\begin{table}[ht]",
        "\\centering",
        "\\caption{RockSample extended results: full agent roster including",
        " a flat one-ply Monte Carlo (Flat-MC) baseline on every instance and Planning+IG at",
        " both $w{=}5$ and $w{=}10$. Steps and checks are episode means.",
        " RS[5,3]/RS[7,4]: 500 episodes $\\times$ 10 seeds. RS[7,8]/RS[11,11]:",
        " 100 episodes $\\times$ 5 seeds.}",
        "\\label{tab:rocksample_extended}",
        "\\begin{small}",
        "\\begin{tabular}{llccccc}",
        "\\toprule",
        "Instance & Agent & Steps & Checks & Good & Bad & Reward \\\\",
        "\\midrule",
    ]
    for instance, fname, depth in INSTANCES:
        df = load(fname)
        rows = []
        for template in EXT_AGENT_ORDER:
            label = template.format(d=depth)
            match = df[df["agent"] == label]
            if match.empty:
                continue
            rows.append((label, match.iloc[0]))
        lines.append(f"\\multirow{{{len(rows)}}}{{*}}{{{instance}}}")
        for label, r in rows:
            lines.append(
                f" & {label} & ${r['mean_steps']:.2f}$ & ${r['mean_checks']:.2f}$ & "
                f"${r['mean_good']:.2f}$ & ${r['mean_bad']:.2f}$ & {fmt_reward(r)} \\\\"
            )
        lines.append("\\midrule" if instance != INSTANCES[-1][0] else "\\bottomrule")
    if lines[-1] == "\\midrule":
        lines[-1] = "\\bottomrule"
    lines += ["\\end{tabular}", "\\end{small}", "\\end{table}", ""]
    return "\n".join(lines)


def main() -> None:
    TABLES.mkdir(parents=True, exist_ok=True)
    main_tex = build_main_table()
    ext_tex = build_extended_table()
    (TABLES / "rocksample_main.tex").write_text(main_tex)
    (TABLES / "rocksample_extended.tex").write_text(ext_tex)
    print(main_tex)
    print()
    print(ext_tex)
    print(f"\nSaved paper/tables/rocksample_main.tex and rocksample_extended.tex")


if __name__ == "__main__":
    main()
