#!/usr/bin/env python3
"""
Horizon map (Section 4.5 of the review-response plan): breaks the existing
near-optimality-vs-horizon Monte Carlo study (results_nearopt_horizon.csv,
generated by run_nearopt_horizon.py) down by all three sampled regime axes
(reward asymmetry alpha, observation informativeness via accuracy p, and
observation cost), and reports the per-environment agreement between the
H=1 near-optimality classification and the H>=2 classification.

This is an empirical boundary map, not an adaptive-submodularity theorem:
it reports where the H=1 check over- or under-predicts w=1's behavior under
deeper planning, using the same 100 environments and the same near-optimal
criterion already in the main text (Section "When is w=1 near-optimal?").
"""

from __future__ import annotations

import sys
from pathlib import Path

import pandas as pd

_ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(_ROOT))

RESULTS = _ROOT / "results"
TABLES = _ROOT / "paper" / "tables"

ALPHA_BINS = [(1, 3, "alpha<3"), (3, 10, "3<=alpha<10"), (10, 51, "alpha>=10")]
P_BINS = [(0.55, 0.65, "p<0.65"), (0.65, 0.85, "0.65<=p<0.85"), (0.85, 0.96, "p>=0.85")]
COST_BINS = [(0.1, 1.0, "cost<1"), (1.0, 3.0, "1<=cost<3"), (3.0, 5.01, "cost>=3")]

# LaTeX-rendered forms of the same bin labels, for the generated table only.
_TEX_LABELS = {
    "alpha<3": r"$\alpha<3$",
    "3<=alpha<10": r"$3 \le \alpha < 10$",
    "alpha>=10": r"$\alpha \ge 10$",
    "p<0.65": r"$p<0.65$",
    "0.65<=p<0.85": r"$0.65 \le p < 0.85$",
    "p>=0.85": r"$p \ge 0.85$",
    "cost<1": r"cost$<1$",
    "1<=cost<3": r"$1 \le$ cost$<3$",
    "cost>=3": r"cost$\ge 3$",
}
_TEX_AXIS_NAMES = {
    "alpha (reward asymmetry)": r"$\alpha$ (reward asymmetry)",
    "p (observation informativeness)": r"$p$ (observation informativeness)",
    "cost (observation cost)": "cost (observation cost)",
}


def regime_table(df: pd.DataFrame, col: str, bins) -> pd.DataFrame:
    rows = []
    for lo, hi, label in bins:
        mask = (df[col] >= lo) & (df[col] < hi)
        sub = df[mask]
        row = {"regime": label, "n_envs": sub["env_id"].nunique()}
        for h in sorted(df["horizon"].unique()):
            hm = sub[sub["horizon"] == h]
            row[f"H={h}"] = float(hm["near_optimal"].mean()) if len(hm) else float("nan")
        rows.append(row)
    return pd.DataFrame(rows)


def agreement_summary(df: pd.DataFrame) -> dict:
    piv = df.pivot(index="env_id", columns="horizon", values="near_optimal")
    h1 = piv[1]
    deeper_cols = [h for h in piv.columns if h >= 2]
    h_deep = piv[deeper_cols].any(axis=1)  # near-optimal at ANY deeper horizon

    both_true = int((h1 & h_deep).sum())
    both_false = int((~h1 & ~h_deep).sum())
    myopic_overclaims = int((h1 & ~h_deep).sum())  # H=1 says fine, no deeper H agrees
    myopic_underclaims = int((~h1 & h_deep).sum())  # H=1 says no, some deeper H says fine
    n = len(piv)

    max_h = max(deeper_cols)
    monotone_frac = float(
        (piv[1].astype(int) <= piv[2].astype(int)).mean()
        if 2 in piv.columns
        else float("nan")
    )

    return {
        "n_envs": n,
        "agree_near_optimal": both_true,
        "agree_not_near_optimal": both_false,
        "myopic_overclaims": myopic_overclaims,  # H=1 near-opt but never again at H>=2
        "myopic_underclaims": myopic_underclaims,  # H=1 not near-opt but is at some H>=2
        "agreement_rate": (both_true + both_false) / n,
        "monotone_h1_le_h2_rate": monotone_frac,
        "max_horizon": max_h,
    }


def main() -> None:
    csv_path = RESULTS / "results_nearopt_horizon.csv"
    if not csv_path.exists():
        raise SystemExit(f"Missing {csv_path}; run experiments/run_nearopt_horizon.py first")
    df = pd.read_csv(csv_path)

    tables = {
        "alpha (reward asymmetry)": regime_table(df, "alpha", ALPHA_BINS),
        "p (observation informativeness)": regime_table(df, "p", P_BINS),
        "cost (observation cost)": regime_table(df, "cost", COST_BINS),
    }
    for name, t in tables.items():
        print(f"\n=== {name} ===")
        print(t.to_string(index=False))

    agreement = agreement_summary(df)
    print("\n=== H=1 vs H>=2 agreement (same 100 environments) ===")
    for k, v in agreement.items():
        print(f"  {k}: {v}")

    # Backing CSVs.
    for name, t in tables.items():
        slug = name.split()[0].replace("(", "").replace(")", "")
        t.to_csv(RESULTS / f"results_horizon_map_{slug}.csv", index=False)
    pd.DataFrame([agreement]).to_csv(RESULTS / "results_horizon_map_agreement.csv", index=False)
    print(f"\nSaved results/results_horizon_map_*.csv")

    # LaTeX table: one combined regime map + the agreement footnote row.
    TABLES.mkdir(parents=True, exist_ok=True)
    horizons = sorted(df["horizon"].unique())
    lines = [
        "% Auto-generated by experiments/build_horizon_map.py -- do not edit by hand.",
        "\\begin{table}[t]",
        "\\centering",
        "\\caption{Horizon map: fraction of randomly generated two-state environments",
        " where $w{=}1$ is near-optimal (within $\\max(5\\%, 0.5)$ of the",
        " reward-optimal weight), stratified by each sampled regime axis and",
        " planning horizon $H$. Same 100 environments as Figure~\\ref{fig:nearopt_horizon}" ,
        " (Appendix~\\ref{app:nearopt_horizon}); this is an empirical boundary map, not an",
        " adaptive-submodularity guarantee.}",
        "\\label{tab:horizon-map}",
        "\\small",
        "\\begin{tabular}{l" + "c" * len(horizons) + "}",
        "\\toprule",
        "Regime & " + " & ".join(f"$H{{=}}{h}$" for h in horizons) + " \\\\",
        "\\midrule",
    ]
    for name, t in tables.items():
        axis_tex = _TEX_AXIS_NAMES.get(name, name)
        lines.append(f"\\multicolumn{{{len(horizons) + 1}}}{{l}}{{\\textit{{{axis_tex}}}}} \\\\")
        for _, r in t.iterrows():
            vals = " & ".join(f"{r[f'H={h}']*100:.0f}\\%" for h in horizons)
            label_tex = _TEX_LABELS.get(r["regime"], r["regime"])
            lines.append(f"\\quad {label_tex} & {vals} \\\\")
    lines += ["\\bottomrule", "\\end{tabular}"]
    lines.append(
        f"\\par\\vspace{{2pt}}\\footnotesize $H{{=}}1$ vs.\\ $H{{\\geq}}2$ agreement: "
        f"{agreement['agreement_rate']*100:.0f}\\% of {agreement['n_envs']} environments "
        f"agree; myopic overclaims {agreement['myopic_overclaims']}, "
        f"underclaims {agreement['myopic_underclaims']}."
    )
    lines += ["\\end{table}", ""]
    out_tex = TABLES / "horizon_map.tex"
    out_tex.write_text("\n".join(lines))
    print(f"Saved {out_tex}")


if __name__ == "__main__":
    main()
