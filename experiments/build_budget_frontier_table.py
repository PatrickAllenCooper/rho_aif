"""Build paper/tables/budget_frontier.tex from results_budget_frontier.csv.

One row per environment and attainable budget for the endpoint mixture, with
the best budget-feasible single weight, the two LP-selected mixtures over the
calibration grid (best target mixture at usage exactly B, best feasible
mixture at usage at most B), and the near-optimal constrained reference's
estimated feasible envelope beside it. Unattainable budgets are listed as
declared. This is the only producer of that table (ledger 9.17.45, amended
9.17.46 for the envelope reference and the two LP mixtures).
"""
from __future__ import annotations

import sys
from pathlib import Path

import numpy as np
import pandas as pd

_ROOT = Path(__file__).resolve().parents[1]
RESULTS, TABLES = _ROOT / "results", _ROOT / "paper" / "tables"
KIND = {"interior_0.25": "0.25 of range", "interior_0.5": "0.50 of range", "interior_0.75": "0.75 of range", "gap": "gap", "unattainable": "below $U_{\\min}$"}


def fmt(x, se=None, d=2):
    if x is None or (isinstance(x, float) and np.isnan(x)):
        return "--"
    return f"${x:.{d}f} \\pm {se:.{d}f}$" if se is not None and not np.isnan(se) else f"${x:.{d}f}$"


def main():
    e = pd.read_csv(RESULTS / "results_budget_frontier.csv")
    hr = pd.read_csv(RESULTS / "results_budget_frontier_heldout_reference.csv")
    hr = hr[hr.policy == "mixture"].set_index(["env", "budget_kind"])
    # Three continued panels retain all twelve original columns at one
    # physical font size.  No scaling box may shrink the table contents.
    captions = [
        "The calibrated family at calibration-derived target budgets, set by a predeclared rule from each calibration curve and evaluated on five held-out seeds it was not calibrated on ($100$ episodes per seed, seed-level SE). Budgets are set from each calibration curve's attainable range $[U_{\\min}, U_{\\max}]$ at three fractions of the range, at the midpoint of the largest jump (gap), and below $U_{\\min}$ (declared unattainable, not run). The mixture plays the bracket's upper endpoint with probability $q$ and its lower endpoint otherwise, drawn afresh each episode. Usage is the observation count. See \\texttt{results\\_budget\\_frontier.csv} and \\texttt{results\\_budget\\_frontier\\_heldout\\_reference.csv}.",
        "The calibrated family (continued). Held-out reward comparisons within the calibration grid. Best member is the calibration-grid weight with the highest calibration reward among those whose calibration usage is at or below $B$. Target mixture is the reward-maximizing mixture of calibration-grid weights whose calibration usage equals $B$, and feasible mixture the same with usage at most $B$, each a linear program with at most two support weights, selected on the calibration data and run on the held-out seeds.",
        "The calibrated family (continued). Constrained-reference comparisons. The reference is the estimated feasible envelope of the near-optimal constrained-POMDP reference of Section~\\ref{sec:cpomdp}, the largest reward attainable by mixing its sampled points subject to expected usage at most $B$, flat at the largest sampled reward where $B$ exceeds the largest sampled usage. That reference was evaluated on the canonical seeds with once-per-seed seeding. Same-stream reference is the same envelope with every sampled reference policy re-evaluated on the held-out seeds under the family's per-episode seeding, and paired gap is the mixture's reward minus that envelope, per seed, with its seed-level SE. Reference support and mixture weights are fitted on those same held-out seed means and held fixed for the SE. The nominal pointwise plug-in intervals discussed in the text omit uncertainty from that fit and cap feasibility, and make no multiplicity adjustment.",
    ]
    headers = [
        r"Env. & Budget & $B$ & $q$ & \shortstack{Mixture\\usage} & \shortstack{Mixture\\reward} \\",
        r"Env. & Budget & \shortstack{Best\\member} & \shortstack{Target\\mixture} & \shortstack{Feasible\\mixture} \\",
        r"Env. & Budget & Reference & \shortstack{Same-stream\\reference} & Paired gap \\",
    ]
    lines = ["% Auto-generated by experiments/build_budget_frontier_table.py -- do not edit by hand.", ""]
    for panel in range(3):
        lines += [r"\begin{table}[t]", r"\centering"]
        if panel:
            lines += [r"\addtocounter{table}{-1}",
                      r"\renewcommand{\theHtable}{\arabic{table}." + str(panel + 1) + "}"]
        lines.append("\\caption{" + captions[panel] + "}")
        if not panel:
            lines.append(r"\label{tab:budget_frontier}")
        lines += ["%% Numbers produced by experiments/run_budget_frontier.py and experiments/run_frontier_reference_heldout.py",
                  r"\tablefontsize", r"\setlength{\tabcolsep}{3pt}",
                  r"\begin{tabular}{@{}ll" + "c" * (4 if panel == 0 else 3) + "@{}}",
                  r"\toprule", headers[panel], r"\midrule"]
        for env in ["Tiger", "Diagnosis", "Bandit"]:
            g = e[e.env == env]
            for kind in ["interior_0.25", "interior_0.5", "interior_0.75", "gap", "unattainable"]:
                h = g[g.budget_kind == kind]
                if h.empty:
                    continue
                B = float(h.iloc[0]["budget"])
                if kind == "unattainable":
                    rest = f"${B:.2f}$ & -- & \\multicolumn{{2}}{{l}}{{declared unattainable}}" if panel == 0 else r"\multicolumn{3}{l}{declared unattainable}"
                    lines.append(f"{env} & {KIND[kind]} & {rest} \\\\")
                    continue
                m = h[h.policy == "mixture"].iloc[0]
                def pol(name):
                    r = h[h.policy == name]
                    if r.empty or np.isnan(float(r.iloc[0]["heldout_reward"])):
                        return "--"
                    return fmt(float(r.iloc[0]["heldout_reward"]), float(r.iloc[0]["heldout_reward_se"]))
                if panel == 0:
                    cells = [fmt(B), fmt(float(m["q"])),
                             fmt(float(m["heldout_usage"]), float(m["heldout_usage_se"])),
                             fmt(float(m["heldout_reward"]), float(m["heldout_reward_se"]))]
                elif panel == 1:
                    cells = [pol("best_feasible_member"), pol("best_target_mixture"), pol("best_feasible_mixture")]
                else:
                    ref = float(m["reference_envelope_at_B"])
                    cells = [fmt(ref if not np.isnan(ref) else None),
                             fmt(float(hr.loc[(env, kind), "heldout_reference"])),
                             fmt(float(hr.loc[(env, kind), "paired_gap"]), float(hr.loc[(env, kind), "paired_gap_se"]))]
                lines.append(" & ".join([env, KIND[kind]] + cells) + r" \\")
            lines.append(r"\midrule")
        lines[-1] = r"\bottomrule"
        lines += [r"\end{tabular}", r"\end{table}", ""]
    out = TABLES / "budget_frontier.tex"
    out.write_text("\n".join(lines))
    print(f"Saved {out}")


if __name__ == "__main__":
    main()
